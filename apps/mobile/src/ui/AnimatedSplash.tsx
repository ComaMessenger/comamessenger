import { useEffect } from "react";
import { StyleSheet, useColorScheme, useWindowDimensions } from "react-native";
import Animated, {
  runOnJS,
  useAnimatedProps,
  useAnimatedStyle,
  useDerivedValue,
  useFrameCallback,
  useReducedMotion,
  useSharedValue,
} from "react-native-reanimated";
import Svg, { Path } from "react-native-svg";
import { mascot, mascotColors } from "@comamessenger/tokens";
import {
  REST_POSE,
  SPLASH_FINALE,
  bodyPath,
  doneAt,
  eyesPath,
  feetPath,
  splashPose,
  trackPath,
} from "./splashWalk";

const AnimatedPath = Animated.createAnimatedComponent(Path);

// Geometry generated by design/brand/generate.mjs, which also draws the static
// splash image this overlay continues.
const BOX = mascot.viewBox.regular;

// The native splash shows splash-icon.png 200 pt wide with the mascot taking
// SPLASH_MASCOT_HEIGHT of it; the overlay starts from exactly that frame.
const SPLASH_IMAGE_WIDTH = 200;
const SPLASH_MASCOT_HEIGHT = 0.6;
/** Points per mascot unit. */
const SCALE = (SPLASH_IMAGE_WIDTH * SPLASH_MASCOT_HEIGHT) / BOX.height;
const CENTER_X = BOX.x + BOX.width / 2;
const CENTER_Y = BOX.y + BOX.height / 2;

/**
 * Continues the native splash screen: the mascot stands up and walks in place
 * on a running track, towing a message bubble, while the app loads. Once
 * `ready`, it stops on the next footfall and the overlay fades into the first
 * screen (see SPLASH_FINALE in ./splashWalk).
 *
 * `onShown` fires once the overlay is on screen, so the native splash can be
 * hidden without a blank frame; `onDone` fires after the fade-out.
 */
export function AnimatedSplash({
  ready,
  onShown,
  onDone,
}: {
  ready: boolean;
  onShown: () => void;
  onDone: () => void;
}) {
  const colors = mascotColors[useColorScheme() === "dark" ? "dark" : "light"];
  const reduceMotion = useReducedMotion();
  const { width, height } = useWindowDimensions();

  const start = useSharedValue(-1);
  const clock = useSharedValue(0);
  const readyAt = useSharedValue(Infinity);
  const reduced = useSharedValue(reduceMotion);
  const finished = useSharedValue(false);

  useEffect(() => {
    reduced.value = reduceMotion;
  }, [reduceMotion, reduced]);

  useEffect(() => {
    if (ready && readyAt.value === Infinity) readyAt.value = clock.value;
  }, [ready, readyAt, clock]);

  // Own start time, so re-registering the callback never restarts the walk.
  useFrameCallback(({ timestamp }) => {
    if (finished.value) return;
    if (start.value < 0) start.value = timestamp;
    const t = timestamp - start.value;
    clock.value = t;
    if (t >= doneAt(readyAt.value, SPLASH_FINALE, reduced.value)) {
      finished.value = true;
      runOnJS(onDone)();
    }
  });

  const pose = useDerivedValue(() =>
    splashPose(clock.value, readyAt.value, SPLASH_FINALE, reduced.value),
  );
  // Wide enough for any phone; the path is clipped by the screen anyway.
  const half = Math.ceil(Math.max(width, height) / SCALE / 2);

  const bodyProps = useAnimatedProps(() => ({ d: bodyPath(pose.value) }));
  const eyesProps = useAnimatedProps(() => ({ d: eyesPath(pose.value) }));
  const feetProps = useAnimatedProps(() => ({ d: feetPath(pose.value) }));
  const trackA = useAnimatedProps(() => ({
    d: trackPath(pose.value, 0, half),
  }));
  const trackB = useAnimatedProps(() => ({
    d: trackPath(pose.value, 1, half),
  }));
  const overlayStyle = useAnimatedStyle(() => ({
    opacity: pose.value.opacity,
  }));

  // The view box keeps the mascot exactly where and how big the native splash
  // drew it: centred, SCALE points per unit.
  const viewBox = [
    CENTER_X - width / SCALE / 2,
    CENTER_Y - height / SCALE / 2,
    width / SCALE,
    height / SCALE,
  ].join(" ");

  return (
    <Animated.View
      accessible={false}
      importantForAccessibility="no-hide-descendants"
      pointerEvents="none"
      onLayout={onShown}
      style={[
        StyleSheet.absoluteFill,
        styles.overlay,
        { backgroundColor: colors.plate },
        overlayStyle,
      ]}
    >
      <Svg style={StyleSheet.absoluteFill} viewBox={viewBox}>
        <AnimatedPath
          d={trackPath(REST_POSE, 0, half)}
          animatedProps={trackA}
          fill={colors.body}
          fillOpacity={0.22}
        />
        <AnimatedPath
          d={trackPath(REST_POSE, 1, half)}
          animatedProps={trackB}
          fill={colors.body}
          fillOpacity={0.36}
        />
        <AnimatedPath
          d={feetPath(REST_POSE)}
          animatedProps={feetProps}
          fill={colors.feet}
        />
        <AnimatedPath
          d={bodyPath(REST_POSE)}
          animatedProps={bodyProps}
          fill={colors.body}
        />
        <AnimatedPath
          d={eyesPath(REST_POSE)}
          animatedProps={eyesProps}
          fill={colors.eyes}
        />
      </Svg>
    </Animated.View>
  );
}

const styles = StyleSheet.create({
  overlay: { zIndex: 1000 },
});
